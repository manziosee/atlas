// Writes out/_redirects after `next build`. The operations area is reachable
// only at /<ATLAS_OPS_PATH>/, a secret set in the hosting environment and
// never committed. Direct requests to /ops always get a 404, and without
// ATLAS_OPS_PATH the area is not reachable at all.
import { writeFileSync } from "node:fs";

const slug = (process.env.ATLAS_OPS_PATH ?? "").trim().replace(/^\/+|\/+$/g, "");
const lines = ["# Generated by scripts/write-redirects.mjs"];
if (slug) {
  if (!/^[A-Za-z0-9-]{16,64}$/.test(slug)) {
    console.error("ATLAS_OPS_PATH must be 16-64 letters, digits or hyphens.");
    process.exit(1);
  }
  lines.push(`/${slug}    /ops/index.html    200!`, `/${slug}/   /ops/index.html    200!`);
}
lines.push("/ops        /404.html          404!", "/ops/*      /404.html          404!", "");
writeFileSync(new URL("../out/_redirects", import.meta.url), lines.join("\n"));
console.log(slug ? "Operations area enabled at its configured path." : "Operations area disabled (ATLAS_OPS_PATH unset).");
